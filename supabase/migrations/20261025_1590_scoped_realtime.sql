 insert into public.myb_realtime_events(family_id,event_kind,scope,transaction_key,created_at)
 values(oldfid,'scoped_write',tg_argv[0],stamp,clock_timestamp())
 on conflict(family_id,transaction_key,scope) where transaction_key is not null do nothing;
 end if;end if;
