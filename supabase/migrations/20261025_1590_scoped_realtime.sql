create or replace function public.myb_realtime_revision_v1590(p_sync_id text) returns jsonb
language sql stable security definer set search_path=public,pg_temp as $$
 select jsonb_build_object('ok',true,'versions',coalesce(jsonb_object_agg(scope,rev),'{}'::jsonb)) from (
 select scope,count(*)::text||':'||max(id)::text rev from public.myb_realtime_events
 where family_id=public.myb_stable_uuid('family:'||p_sync_id) group by scope) r;
$$;
