/* Node test — medication reminders: independent queues, snooze, manual completion. */
const assert=require('node:assert/strict');
const core=require('../src/features/notifications/medication-core.js');
const day='2026-11-24';
const d=(hour,minute)=>new Date(2026,10,24,hour,minute,0);
const r1={id:'r1',name:'D3K2',dose:6,unit:'giọt',start:'08:00',end:'',active:true};
const r2={id:'r2',name:'Vitamin C',dose:1,unit:'ml',start:'10:00',end:'',active:true};
const cfg={enabled:true,items:[r1,r2]};
const ids=(when,records={},events=[])=>core.due(cfg,events,{records},when).map(x=>x.rule.id);
assert.equal(core.dayKey(d(10,0)),day);
assert.deepEqual(ids(d(7,59)),[]);
assert.deepEqual(ids(d(8,0)),['r1']);
assert.deepEqual(ids(d(10,0)),['r1','r2']);
let state={[day+'|r1']:{nextAt:d(10,10).getTime()}};
assert.deepEqual(ids(d(10,1),state),['r2']);
state[day+'|r2']={nextAt:d(10,11).getTime()};
assert.deepEqual(ids(d(10,2),state),[]);
assert.deepEqual(ids(d(10,10),state),['r1']);
assert.deepEqual(ids(d(10,11),state),['r1','r2']);
assert.deepEqual(ids(d(10,11),{[day+'|r1']:{done:true}},[]),['r2']);
assert.deepEqual(core.due({enabled:false,items:[r1]},[],{},d(10,0)),[]);
assert.deepEqual(ids(new Date(2026,10,25,0,1)),[]);
const event=(id,name,dose,unit,time,ruleId)=>({id:id,type:'medicine',date:day,startDate:day,timeFrom:time,amount:dose,unit:unit,extra:{name:name,...ruleId?{medicationReminderId:ruleId}:{}}});
assert.deepEqual(ids(d(10,2),{},[event('e1','D3K2',6,'giọt','08:24','r1')]),['r2']);
const same={enabled:true,items:[r1,{...r1,id:'r3',start:'10:00'}]};
let done=core.completed(same,[event('e2','D3K2',6,'giọt','10:05')],day);
assert.deepEqual([...done],['r3']);
done=core.completed(same,[event('e1','D3K2',6,'giọt','08:05'),event('e2','D3K2',6,'giọt','10:05')],day);
assert.deepEqual([...done].sort(),['r1','r3']);
assert.equal(core.matching(event('e','D3K2',6,'giọt','07:59'),r1,day),false);
assert.equal(core.matching(event('e','D3K2',6,'giọt','09:59'),r1,day),true);
const to={...r1,end:'08:30'};
assert.equal(core.due({enabled:true,items:[to]},[],{},d(8,31)).length,0);
assert.equal(core.due({enabled:true,items:[to]},[],{},d(8,30)).length,1);
for(const item of [{...r1,dose:0},{...r1,start:''},{...r1,end:'07:00'},{...r1,unit:''}])assert.throws(()=>core.validate(item));
assert.equal(core.validate({...r1}).name,'D3K2');
console.log('PASS medication reminder V17.22.61 — independent 08/10 queue, 10-minute snooze, end window, manual completion, validation');
